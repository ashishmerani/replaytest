/**
 * Tests-tab generated-spec guidance fold — rendered-truth probe.
 *
 * The Tests tab folds each generated spec's leading guidance banner (collapsed
 * by default) while keeping the spec-specific recorded-facts block always
 * visible. The fold hides/shows the banner via an `.open` class that flips a
 * `display: none` rule — a CSS-cascade conflict can leave an expected-hidden
 * element visibly rendered even though its DOM class state is correct. The
 * regex + fake-DOM component harness (server.test.ts) cannot see that. This probe drives the REAL
 * served page and asserts COMPUTED visibility (getComputedStyle), not attribute
 * or class presence:
 *   - the banner body computes `display: none` while collapsed,
 *   - the recorded-facts block is visible the whole time (never foldable),
 *   - clicking the real fold bar makes the banner body computed-visible,
 *   - clicking again re-hides it.
 *
 * The probe seeds one generated spec into the worker's scratch workspace
 * (`server.ts` enumerates `tests/generated/` live per `/api/tests` request), so
 * it never touches this repo's real specs.
 */

import * as fs from 'node:fs';
import * as path from 'node:path';

import { expect, test } from './fixtures.js';

const PROBE_SPEC_NAME = 'fold-probe.spec.ts';
const PROBE_SPEC = [
  '// replaytest-slug: fold-probe',
  '// Generated by replaytest from a REAL production session on your app.',
  '// This is a test scaffold: your code-aware coding agent finishes it.',
  '//   5. Relative page.goto() paths need Playwright config use.baseURL.',
  '',
  "import { test, expect } from '@playwright/test';",
  '',
  '// Data requirements:',
  '// First seen after a form submit — likely created by this journey:',
  '//   - /customers/cust-6175 (pattern /customers/:id)',
  '',
  '// Recording findings (from the session data — surfaced, never assertions):',
  '//   - Session capture masks and drops sensitive required fields.',
  '',
  'test.use({ viewport: { width: 1280, height: 720 } });',
  '',
  "test('Cust 6175', async ({ page }) => {",
  "  await page.goto('/');",
  '});',
  '',
].join('\n');

test('the generated-spec banner folds by COMPUTED visibility while the recorded-facts block stays visible', async ({ page, dashboardBaseUrl, dashboardWorkspaceDir }) => {
  const generatedDir = path.join(dashboardWorkspaceDir, 'tests', 'generated');
  fs.mkdirSync(generatedDir, { recursive: true });
  fs.writeFileSync(path.join(generatedDir, PROBE_SPEC_NAME), PROBE_SPEC, 'utf8');

  await page.goto(`${dashboardBaseUrl}/`);
  await page.locator('.tab-btn[data-tab="tests"]').click();
  await page.locator(`#tests-list .list-item[data-name="${PROBE_SPEC_NAME}"]`).click();

  const foldBar = page.locator('.spec-fold-bar');
  const foldBody = page.locator('.spec-fold-body');
  const facts = page.locator('.spec-facts');
  const count = page.locator('.spec-fold-count');

  await expect(foldBar).toBeVisible();
  // Real computed count (4 comment lines + trailing blank before the import).
  await expect(count).toHaveText('5 lines');

  // Collapsed by default: the banner body computes display:none…
  await expect(foldBody).toHaveCSS('display', 'none');
  await expect(foldBar).toHaveAttribute('aria-expanded', 'false');
  // …while the recorded-facts block is genuinely visible the whole time.
  await expect(facts).toBeVisible();
  await expect(facts).toContainText("This test's recorded facts");

  // Click expands — computed display flips to block (real cascade, not [class] presence).
  await foldBar.click();
  await expect(foldBody).toHaveCSS('display', 'block');
  await expect(foldBody).toBeVisible();
  await expect(foldBody).toContainText('// replaytest-slug: fold-probe');
  await expect(foldBar).toHaveAttribute('aria-expanded', 'true');

  // Click again re-hides.
  await foldBar.click();
  await expect(foldBody).toHaveCSS('display', 'none');
  await expect(foldBar).toHaveAttribute('aria-expanded', 'false');
});
