export function seedParityWorkspace(workspaceDir: string): void {
  const plansDir = path.join(workspaceDir, '.replaytest', 'plans');
  const generatedDir = path.join(workspaceDir, 'tests', 'generated');
  const retiredDir = path.join(workspaceDir, '.replaytest', 'retired', 'fixture-record');
  const cacheDir = path.join(workspaceDir, '.replaytest', 'cache');
  fs.mkdirSync(plansDir, { recursive: true });
  fs.mkdirSync(generatedDir, { recursive: true });
  fs.mkdirSync(retiredDir, { recursive: true });
  fs.mkdirSync(cacheDir, { recursive: true });
  fs.writeFileSync(path.join(plansDir, `${PLAN_SLUG}.plan.json`), JSON.stringify(PLAN_SIDECAR, null, 2) + '\n');
  fs.writeFileSync(path.join(generatedDir, GENERATED_NAME), GENERATED_SPEC);
  fs.writeFileSync(path.join(retiredDir, 'retirement.json'), JSON.stringify(RETIREMENT_RECORD, null, 2) + '\n');
  fs.writeFileSync(path.join(cacheDir, 'dashboard-last-scan.json'), JSON.stringify({
    version: 2,
    identity: { host: 'fixture.local', projectId: 'fixture-project' },
    filterKey: 'fixture',
    payloadSchemaVersion: 5,
    payload: paritySessionsResponse(),
  }) + '\n');
}

async function jsonRoute(route: Route, body: unknown, delayMs = 0): Promise<void> {
  if (delayMs > 0) await new Promise((resolve) => setTimeout(resolve, delayMs));
  await route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(body) });
}

/** How long a deliberately-slow re-check takes to answer. The "working" phase of a status
 *  chip has to be observable by a test that is sharing the machine with other workers, so the
 *  window is wide enough to be seen without being long enough to matter. */
const RECHECK_DELAY_MS = 750;

/** Fulfills dashboard data locally so no provider endpoint is contacted. */
export async function installParityRoutes(page: Page): Promise<void> {
  await page.route('**/api/sessions**', (route) => jsonRoute(route, paritySessionsResponse(), route.request().url().includes('check=1') ? RECHECK_DELAY_MS : 0));
  await page.route('**/api/suite-health**', (route) => jsonRoute(route, paritySuiteHealthResponse(), route.request().url().includes('refresh=1') ? RECHECK_DELAY_MS : 0));
  await page.route('**/api/plans', (route) => jsonRoute(route, parityPlansResponse()));
  await page.route('**/api/tests', (route) => jsonRoute(route, parityTestsResponse()));
  await page.route('**/api/tests/*', (route) => jsonRoute(route, { kind: 'readable', name: GENERATED_NAME, slug: PLAN_SLUG, content: GENERATED_SPEC }));
  await page.route('**/api/retired', (route) => jsonRoute(route, parityRetiredResponse()));
  await page.route('**/api/replay-availability', (route) => jsonRoute(route, { availability: {}, checkedAt: FROZEN_NOW }));
  await page.route('**/api/config', (route) => jsonRoute(route, { projectId: 'fixture-project', hasApiKey: true, host: 'https://us.posthog.com', configured: true, posthogCli: { reachable: false, error: 'fixture' } }));
  await page.route('**/api/dashboard-settings', (route) => jsonRoute(route, { autoCheck: 'never' }));
  await page.route('**/api/scaffold', (route) => jsonRoute(route, { exitCode: 0, stdout: 'Fixture scaffold complete.', stderr: '' }, RECHECK_DELAY_MS));
}

